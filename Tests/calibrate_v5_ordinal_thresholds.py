"""
Validation-only ordinal threshold calibration for MediPredict V5.
Requires v5_validation_predictions.csv generated by analyze_v5_validation.py
Tune on validation only; don't use test or auto_test for calibration.
"""
import csv, itertools, json, os
import numpy as np
from sklearn.metrics import cohen_kappa_score, accuracy_score, balanced_accuracy_score, f1_score, confusion_matrix, classification_report

INPUT_CSV = "v5_validation_predictions.csv"
OUTPUT_JSON = "v5_calibrated_thresholds.json"
GRADES = [0, 1, 2, 3, 4]
THRESHOLDS = np.round(np.arange(0.25, 0.751, 0.025), 3)

def load_data(path):
    y, probs = [], []
    with open(path, newline="", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        required = ["actual_grade", "p_grade_gt_0", "p_grade_gt_1", "p_grade_gt_2", "p_grade_gt_3"]
        missing = [c for c in required if c not in (reader.fieldnames or [])]
        if missing:
            raise ValueError(f"CSV is missing columns: {missing}")
        for row in reader:
            y.append(int(row["actual_grade"]))
            probs.append([float(row[f"p_grade_gt_{k}"]) for k in range(4)])
    return np.asarray(y, dtype=int), np.asarray(probs, dtype=float)

def decode(probs, thresholds):
    decisions = probs >= np.asarray(thresholds)[None, :]
    return decisions.sum(axis=1).astype(int)

def qwk(y, pred):
    return cohen_kappa_score(y, pred, labels=GRADES, weights="quadratic")

def show_metrics(title, y, pred, thresholds):
    print("\\n" + "=" * 64 + "\\n" + title + "\\n" + "=" * 64)
    print("Thresholds P(grade > 0..3):", [round(float(x), 3) for x in thresholds])
    print(f"Accuracy:          {accuracy_score(y, pred):.4f}")
    print(f"Balanced accuracy: {balanced_accuracy_score(y, pred):.4f}")
    print(f"Macro F1:          {f1_score(y, pred, average='macro', zero_division=0):.4f}")
    print(f"Quadratic QWK:     {qwk(y, pred):.4f}")
    cm = confusion_matrix(y, pred, labels=GRADES)
    print("\\nConfusion matrix (rows=actual, columns=predicted):")
    print("       Pred 0  Pred 1  Pred 2  Pred 3  Pred 4")
    for grade, row in enumerate(cm):
        print(f"Actual {grade}  " + "  ".join(f"{v:6d}" for v in row))
    print("\\nPer-grade report:")
    print(classification_report(y, pred, labels=GRADES, target_names=[f"Grade {g}" for g in GRADES], zero_division=0))

def main():
    if not os.path.isfile(INPUT_CSV):
        raise FileNotFoundError(f"{INPUT_CSV} not found. Run analyze_v5_validation.py first with V5 checkpoint.")
    y, probs = load_data(INPUT_CSV)
    if not len(y):
        raise ValueError("Prediction CSV contains no rows.")

    baseline = [0.5] * 4
    base_pred = decode(probs, baseline)
    best_score, best_t, best_pred = -1.0, None, None

    # Exhaustively search nondecreasing cutoffs t0 <= t1 <= t2 <= t3.
    for ts in itertools.combinations_with_replacement(THRESHOLDS, 4):
        pred = decode(probs, ts)
        score = qwk(y, pred)
        if score > best_score:
            best_score, best_t, best_pred = score, [float(t) for t in ts], pred

    print(f"Loaded {len(y)} validation samples from {INPUT_CSV}")
    show_metrics("BASELINE (all cutoffs = 0.5)", y, base_pred, baseline)
    show_metrics("BEST MONOTONIC VALIDATION QWK CUTOFFS", y, best_pred, best_t)

    result = {
        "source": INPUT_CSV,
        "validation_sample_count": int(len(y)),
        "optimization_metric": "quadratic_weighted_kappa",
        "constraint": "t0 <= t1 <= t2 <= t3",
        "thresholds_for_p_grade_gt_0_to_3": best_t,
        "validation_qwk": float(best_score),
        "note": "Validation-calibrated thresholds only. Freeze before a single final test evaluation."
    }
    with open(OUTPUT_JSON, "w", encoding="utf-8") as f:
        json.dump(result, f, indent=2)
    print(f"\\nSaved thresholds to {OUTPUT_JSON}")
    print("Reminder: optimizing on validation may overfit validation; final test evaluation must remain untouched.")

if __name__ == "__main__":
    main()
